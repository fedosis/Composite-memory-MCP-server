async def test_async_acquisition_does_not_block_the_event_loop(lock_root: LockRoot, holder: Any) -> None:
    """The poll must never sleep on the owning event loop (DETAIL §2.2 item 2).

    Baseline contrast clause: the PRE-CHANGE production path polls with
    ``time.sleep(_POLL_INTERVAL_SECONDS)`` on the caller's thread
    (``storage_lock.py:263``), so driving it on the event loop starves every
    other task.  That starvation is measured first and asserted to be real; the
    new coroutine is then asserted not to starve the loop.
    """
    module = _module()
    root = lock_root
    blocker = holder("legacy-ex", root)
    assert blocker["record"]["status"] == "held", blocker["record"]
    with _release_after(blocker, CONTENTION_HOLD):
        blocked_gap, handle = await _ticker_gap(lambda: module._acquire(root.path, "exclusive", 3.0))
    print(f"[contrast] legacy storage_lock.py:263 time.sleep poll: max ticker gap {blocked_gap:.4f}s")
    assert blocked_gap >= 0.5, (
        "the baseline contrast clause did not starve the loop, so it proves nothing: "
        f"max ticker gap {blocked_gap:.4f}s")
    module.fcntl.flock(handle, module.fcntl.LOCK_UN)
    os.close(handle)
    _stop(blocker)

    root2 = _scratch_root("async-nonblocking")
    blocker2 = holder("legacy-ex", root2)
    assert blocker2["record"]["status"] == "held", blocker2["record"]
    with _release_after(blocker2, CONTENTION_HOLD):
        unblocked_gap, lock = await _ticker_gap(
            lambda: module.RuntimeStorageLock.acquire_exclusive_async(root2.path, timeout=3.0))
    print(f"[contract] acquire_exclusive_async: max ticker gap {unblocked_gap:.4f}s")
    assert lock is not None, "the contended acquisition never completed"
    assert unblocked_gap < MAX_LOOP_GAP, (
        "acquire_exclusive_async starved the event loop: every flock must be non-blocking and the "
        f"only await must be the bounded poll sleep (max ticker gap {unblocked_gap:.4f}s)")
    lock.release_exclusive()
    _stop(blocker2)


async def test_async_acquisition_cancellation_never_acquires_ex(lock_root: LockRoot, holder: Any) -> None:
    """A cancelled acquisition leaves no grant and no thread behind (§2.2 item 3)."""
    module = _module()
    root = lock_root
    blocker = holder("legacy-ex", root)
    assert blocker["record"]["status"] == "held", blocker["record"]
    root.pin()
    before_threads = threading.active_count()
    task = asyncio.create_task(module.RuntimeStorageLock.acquire_exclusive_async(root.path, timeout=5.0))
    await asyncio.sleep(0.25)  # the poll loop is mid-flight, descriptor open and unlocked
    task.cancel()
    with pytest.raises(asyncio.CancelledError):
        await task
    assert task.cancelled(), "the cancelled acquisition must not produce a lock"
    assert threading.active_count() == before_threads, (
        "cancellation left a thread/executor behind that could still acquire EX")
    _stop(blocker)
    successor = holder("new", root, timeout=1.0)
    assert successor["record"]["status"] == "held", (
        "a cancelled acquisition still held EX: " + repr(successor["record"]))
    _stop(successor)


def _acquire_coroutine() -> ast.AsyncFunctionDef:
    module = _module()
    tree = ast.parse(Path(module.__file__).read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "RuntimeStorageLock":
            for item in node.body:
                if isinstance(item, ast.AsyncFunctionDef) and item.name == "acquire_exclusive_async":
                    return item
    raise AssertionError("RuntimeStorageLock.acquire_exclusive_async must exist (DETAIL §4.2 step 1)")


def test_acquire_coroutine_has_no_await_after_grant() -> None:
    """AST guard: exactly one await, inside the poll loop, before the grant."""
    coroutine = _acquire_coroutine()
    loops = [node for node in ast.walk(coroutine) if isinstance(node, ast.While)]
    assert len(loops) == 1, "the acquisition must have exactly one polling loop"
    awaits = [node for node in ast.walk(coroutine) if isinstance(node, ast.Await)]
    assert len(awaits) == 1, "exactly one await point is allowed (the bounded poll sleep)"
    target = awaits[0].value
    assert isinstance(target, ast.Call), ast.dump(awaits[0])
    assert ast.unparse(target.func) == "asyncio.sleep"
    assert ast.unparse(target.args[0]) == "_POLL_INTERVAL_SECONDS"
    handlers = [node for node in ast.walk(loops[0]) if isinstance(node, ast.ExceptHandler)]
    retry = [node for node in handlers if ast.unparse(node.type) == "BlockingIOError"]
    assert len(retry) == 1, "contention must be handled as BlockingIOError"
    assert awaits[0] in list(ast.walk(retry[0])), (
        "the only await must be the retry sleep of a FAILED non-blocking flock, so nothing can "
        "await after a successful flock and the sync handover cannot be interrupted")
    for node in ast.walk(loops[0]):
        if isinstance(node, ast.Call) and ast.unparse(node.func) == "fcntl.flock":
            assert "fcntl.LOCK_EX | fcntl.LOCK_NB" in ast.unparse(node), ast.unparse(node)
    assert [node for node in ast.walk(loops[0]) if isinstance(node, ast.Break)], (
        "a successful non-blocking flock must break out of the poll loop")
    for node in ast.walk(coroutine):
        if isinstance(node, ast.Return):
            assert not [child for child in ast.walk(node) if isinstance(child, ast.Await)]


def test_no_executor_or_thread_is_used_for_acquisition(lock_root: LockRoot, holder: Any) -> None:
    """AST guard + thread-count delta: no executor may ever hold an EX grant."""
    module = _module()
    source = Path(module.__file__).read_text(encoding="utf-8")
    banned = ("run_in_executor", "to_thread", "Thread", "ThreadPoolExecutor",
              "ProcessPoolExecutor", "new_event_loop", "run_coroutine_threadsafe")
    body = ast.unparse(_acquire_coroutine())
    found = [name for name in banned if name in body]
    assert not found, f"acquisition must not use {found}"
    assert "run_in_executor" not in source and "to_thread" not in source, (
        "storage_lock.py must contain no deferred-execution acquisition path")
    root = lock_root
    blocker = holder("legacy-sh", root)
    assert blocker["record"]["status"] == "held", blocker["record"]
    root.pin()
    before_threads = threading.active_count()

    async def contended() -> None:
        with pytest.raises(module.StorageLockError) as failure:
            await module.RuntimeStorageLock.acquire_exclusive_async(root.path, timeout=0.3)
        assert failure.value.code == "E_LOCK_TIMEOUT"

    asyncio.run(contended())
    assert threading.active_count() == before_threads, "a thread was created for acquisition"
    _stop(blocker)
    successor = holder("new", root, timeout=1.0)
    assert successor["record"]["status"] == "held", (
        "the failed acquisition leaked its descriptor/EX grant: " + repr(successor["record"]))
    _stop(successor)


def test_release_failure_reports_uncertain_and_retains_descriptor(
    lock_root: LockRoot, holder: Any, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A failed unlock is not a release: stable code, retained descriptor, still excluded."""
    module = _module()
    root = lock_root
    lock = module.RuntimeStorageLock.acquire_exclusive(root.path, timeout=2.0)
    root.pin()
    real_flock = module.fcntl.flock

    def failing_unlock(fd: int, operation: int) -> Any:
        if operation == module.fcntl.LOCK_UN:
            raise OSError(errno.EIO, "synthetic unlock failure")
        return real_flock(fd, operation)

    monkeypatch.setattr(module.fcntl, "flock", failing_unlock)
    with pytest.raises(module.StorageLockError) as failure:
        lock.release_exclusive()
    assert failure.value.code == "E_LOCK_RELEASE_UNCERTAIN"
    assert lock._fh is not None, "the descriptor must be retained, never closed in the error path"
    contender = holder("legacy-ex", root, timeout=0.4)
    assert contender["record"].get("code") == "E_LOCK_TIMEOUT", (
        "a failed release silently dropped the advisory lock: " + repr(contender["record"]))
    monkeypatch.undo()
    lock.release_exclusive()
    assert lock._fh is None
    successor = holder("legacy-ex", root, timeout=1.0)
    assert successor["record"]["status"] == "held", successor["record"]
    _stop(successor)


def test_permission_unsupported_symlink_hardlink_special_and_stale_metadata_fail_closed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Every non-granting condition fails closed with its stable code, in both APIs."""
    module = _module()

    def codes(root: Path) -> tuple[str, str]:
        async def asynchronous() -> str:
            try:
                await module.RuntimeStorageLock.acquire_exclusive_async(root, timeout=0.2)
                return "granted"
            except module.StorageLockError as exc:
                return exc.code

        try:
            module.RuntimeStorageLock.acquire_exclusive(root, timeout=0.2)
            sync = "granted"
        except module.StorageLockError as exc:
            sync = exc.code
        return sync, asyncio.run(asynchronous())

    monkeypatch.setattr(module, "_LOCKING_SUPPORTED", False)
    assert codes(tmp_path / "unsupported") == ("E_LOCK_UNSUPPORTED", "E_LOCK_UNSUPPORTED")
    monkeypatch.undo()
    assert os.geteuid() != 0, "the permission row needs an unprivileged user to be meaningful"
    denied = tmp_path / "denied"
    (denied / "root").mkdir(parents=True)
    os.chmod(denied, 0o000)
    try:
        assert codes(denied / "root") == ("E_LOCK_PERMISSION", "E_LOCK_PERMISSION")
    finally:
        os.chmod(denied, 0o700)

    unsafe = tmp_path / "unsafe"
    unsafe.mkdir()
    target = unsafe / "target"
    target.write_bytes(b"")
    (unsafe / LOCK_ENTRY).symlink_to(target)
    assert codes(unsafe) == ("E_LOCK_ENTRY_UNSAFE", "E_LOCK_ENTRY_UNSAFE")
    (unsafe / LOCK_ENTRY).unlink()
    os.link(target, unsafe / LOCK_ENTRY)
    assert codes(unsafe) == ("E_LOCK_ENTRY_UNSAFE", "E_LOCK_ENTRY_UNSAFE")
    (unsafe / LOCK_ENTRY).unlink()
    os.mkfifo(unsafe / LOCK_ENTRY)
    assert codes(unsafe) == ("E_LOCK_ENTRY_UNSAFE", "E_LOCK_ENTRY_UNSAFE")

    stale = _scratch_root("stale-metadata")
    entry = stale.path / LOCK_ENTRY
    entry.write_text(json.dumps({"pid": 1, "host": "ghost", "mode": "exclusive",
                                 "started_at": "1970-01-01T00:00:00+00:00", "command": "dead"}))
    inode = stale.pin()
    lock = module.RuntimeStorageLock.acquire_exclusive(stale.path, timeout=1.0)
    try:
        assert json.loads(entry.read_bytes())["pid"] == os.getpid(), "a real grant must record its owner"
        assert entry.stat().st_ino == inode, "stale metadata justified replacing the lock inode"
        blocked = codes(stale.path)
        assert blocked == ("E_LOCK_TIMEOUT", "E_LOCK_TIMEOUT"), (
            f"stale metadata let a contender proceed while EX was held: {blocked}")
        assert entry.stat().st_ino == inode
    finally:
        lock.release_exclusive()
    assert entry.exists() and entry.stat().st_ino == inode, "release must keep the entry in place"


def test_identity_swap_is_detected_and_leaks_no_descriptor(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The lock entry is re-verified against the held descriptor after the grant.

    The only row that deliberately swaps the lock entry, on a throwaway root and
    by the test itself; the injected wrapper still calls the real
    ``fcntl.flock`` and only adds a filesystem race.
    """
    module = _module()
    root = tmp_path / "identity-swap"
    root.mkdir()
    entry = root / LOCK_ENTRY
    real_flock = module.fcntl.flock
    swapped = {"done": False}

    def swapping_flock(fd: int, operation: int) -> Any:
        result = real_flock(fd, operation)
        if not swapped["done"] and operation & module.fcntl.LOCK_EX:
            swapped["done"] = True
            entry.unlink()
            entry.write_bytes(b"")
        return result

    monkeypatch.setattr(module.fcntl, "flock", swapping_flock)
    with pytest.raises(module.StorageLockError) as failure:
        module.RuntimeStorageLock.acquire_exclusive(root, timeout=0.5)
    assert failure.value.code == "E_ARTIFACT_IDENTITY_CHANGED"
    monkeypatch.undo()
    assert swapped["done"] is True
    lock = module.RuntimeStorageLock.acquire_exclusive(root, timeout=1.0)
    lock.release_exclusive()
    assert entry.exists(), "release never unlinks the lock entry"


def test_shared_acquire_stays_compatible_for_legacy_callers(lock_root: LockRoot, holder: Any) -> None:
    """PURE CHARACTERIZATION (GREEN on base): ``acquire``/``release`` stay SH."""
    module = _module()
    root = lock_root
    first = holder("legacy-sh", root)
    assert first["record"]["status"] == "held", first["record"]
    root.pin()
    local = module.RuntimeStorageLock.acquire(root.path, timeout=0.5)
    assert first["process"].poll() is None, "legacy SH holders must still coexist"
    assert module.inspect_existing_lock_readonly(root.path).availability == "held"
    local.release()
    with pytest.raises(module.StorageLockError) as failure:
        module.MaintenanceStorageLocks.acquire([root.path], timeout=0.2)
    assert failure.value.code == "E_LOCK_TIMEOUT"
    _stop(first)
    maintenance = module.MaintenanceStorageLocks.acquire([root.path], timeout=1.0)
    maintenance.release()
    assert (root.path / LOCK_ENTRY).exists()
