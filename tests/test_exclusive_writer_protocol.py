def _stop(*handles: dict[str, Any]) -> None:
    """Release every holder and require a clean exit."""
    for handle in handles:
        if handle["process"].poll() is None:
            handle["release"].write_text("go")
    for handle in handles:
        assert handle["process"].wait(timeout=30) == 0


@contextlib.contextmanager
def _release_after(handle: dict[str, Any], delay: float) -> Any:
    """Release a holder after ``delay`` from a helper thread (never the loop)."""
    timer = threading.Timer(delay, handle["release"].write_text, args=("go",))
    timer.start()
    try:
        yield
    finally:
        timer.cancel()


async def _ticker_gap(action: Any) -> tuple[float, Any]:
    """Max gap between ``TICK_SECONDS`` wakeups while ``action`` runs."""
    gaps: list[float] = []
    last = time.monotonic()

    async def ticker() -> None:
        nonlocal last
        while True:
            await asyncio.sleep(TICK_SECONDS)
            now = time.monotonic()
            gaps.append(now - last)
            last = now

    task = asyncio.create_task(ticker())
    try:
        await asyncio.sleep(TICK_SECONDS * 3)  # let the ticker establish a baseline
        result = action()
        if inspect.isawaitable(result):
            result = await result
        # A starved loop wakes the ticker only now; give it one iteration to
        # record the gap it actually suffered before cancellation.
        await asyncio.sleep(TICK_SECONDS)
    finally:
        task.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await task
    return (max(gaps) if gaps else 0.0), result


