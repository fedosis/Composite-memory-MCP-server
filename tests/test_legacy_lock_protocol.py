class PrerequisiteError(RuntimeError):
    """A capture precondition is missing — never a silent skip (§1.3)."""


def _frozen_module_path() -> Path:
    """Resolve the frozen fixture path from the environment on every call."""
    return Path(os.environ.get("CMMS_FROZEN_L1_DIR", str(FROZEN_DIR_DEFAULT))) / "storage_lock.py"


def _require_frozen(path: Path) -> Path:
    if not path.exists():
        raise PrerequisiteError(
            f"frozen legacy lock fixture missing: {path}. {RECAPTURE_HINT}")
    return path


def _root(name: str) -> Path:
    """A fresh lock root inside scratch (never a live data root, §1.2)."""
    root = WORKDIR / "roots" / name
    shutil.rmtree(root, ignore_errors=True)
    root.mkdir(parents=True)
    assert str(root).startswith(str(SCRATCH))
    return root


def _entry_inode(root: Path) -> int:
    return os.stat(root / LOCK_ENTRY).st_ino


